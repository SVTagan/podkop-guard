#!/bin/sh
# Isolated OpenWrt 25.12.6 QEMU integration: REAL Community SRS, REAL sing-box
# cache.db, REAL Guard refresh-test. No user router, Podkop or VPN is touched.
set -eu

grep -q "DISTRIB_RELEASE='25.12.6'" /etc/openwrt_release
[ -r /mnt/pg-bundle/srs/block.srs ] || { echo 'missing SRS fixtures' >&2; exit 1; }
[ -r /mnt/pg-bundle/podkop-guard ]
[ -r /mnt/pg-bundle/srs/geoblock.srs ]
[ ! -e /tmp/pg-srs-cache-e2e ]

# Stock x86 image has its only NIC configured as LAN without a route.
# This is disposable QEMU user-mode NAT, never a user-router change.
guest_if=br-lan
ip link show "$guest_if" >/dev/null 2>&1 || guest_if=eth0
ip link set "$guest_if" up
ip addr add 10.0.2.15/24 dev "$guest_if" 2>/dev/null || true
ip route replace default via 10.0.2.2 dev "$guest_if"
mkdir -p /tmp/resolv.conf.d
printf 'nameserver 10.0.2.3\n' > /tmp/resolv.conf
printf 'nameserver 10.0.2.3\n' > /tmp/resolv.conf.d/resolv.conf.auto
echo "VM_NAT_READY interface=$guest_if"

# Real packages and real HTTP server; no mock programs in PATH.
apk update >/tmp/pg-srs-install.log 2>&1 || {
    echo 'FAIL: apk update inside QEMU' >&2
    cat /tmp/pg-srs-install.log >&2
    exit 1
}
apk add curl jq sing-box uhttpd >>/tmp/pg-srs-install.log 2>&1 || {
    echo 'FAIL: installing real VM-only tools' >&2
    cat /tmp/pg-srs-install.log >&2
    exit 1
}
for package in curl jq sing-box uhttpd; do apk info -e "$package" >/dev/null; done
echo PASS_REAL_MULTI_DEPENDENCIES

TEST_DIR=/tmp/pg-srs-cache-e2e
STATE="$TEST_DIR/lkg"
mkdir -p "$STATE" /tmp/sing-box
chmod 0700 "$TEST_DIR"
# Preexisting LKG data are sentinels, not generated by the test. They must
# never be overwritten by either positive or negative refresh-test calls.
printf 'PRESERVED_SRS\n' > "$STATE/lkg.srs"
printf '203.0.113.0/24\n' > "$STATE/lkg-subnets.lst"
printf 'PRESERVED_CACHE\n' > "$STATE/cache.db"
cp "$STATE/lkg.srs" "$TEST_DIR/lkg-before.srs"
cp "$STATE/lkg-subnets.lst" "$TEST_DIR/subnets-before.lst"
cp "$STATE/cache.db" "$TEST_DIR/cache-before.db"

verify_unchanged() {
    cmp -s "$TEST_DIR/lkg-before.srs" "$STATE/lkg.srs"
    cmp -s "$TEST_DIR/subnets-before.lst" "$STATE/lkg-subnets.lst"
    cmp -s "$TEST_DIR/cache-before.db" "$STATE/cache.db"
}

HTTP_PID=""
SING_PID=""
cleanup() {
    [ -z "$SING_PID" ] || { kill "$SING_PID" 2>/dev/null || true; wait "$SING_PID" 2>/dev/null || true; }
    [ -z "$HTTP_PID" ] || { kill "$HTTP_PID" 2>/dev/null || true; wait "$HTTP_PID" 2>/dev/null || true; }
}
trap cleanup EXIT INT TERM

# Serve SHA-verified original itdoginfo/allow-domains 2026-11-09_19-01
# binaries locally. The *real sing-box* downloads and caches four tags.
uhttpd -f -p 127.0.0.1:18877 -h /mnt/pg-bundle/srs \
    > "$TEST_DIR/http.log" 2>&1 &
HTTP_PID=$!
ready=0
i=0
while [ "$i" -lt 12 ]; do
    if curl -4 -fsS --max-time 2 'http://127.0.0.1:18877/block.srs' \
        -o "$TEST_DIR/served-block.srs"; then
        ready=1
        break
    fi
    sleep 1
    i=$((i + 1))
done
[ "$ready" -eq 1 ] || { cat "$TEST_DIR/http.log" >&2; echo 'HTTP fixture server unavailable' >&2; exit 1; }
cmp -s /mnt/pg-bundle/srs/block.srs "$TEST_DIR/served-block.srs"
echo PASS_REAL_COMMUNITY_SRS_SERVER

# Create actual UCI values used by Guard; these exist ONLY inside QEMU.
[ -e /etc/config/podkop ] || : > /etc/config/podkop
uci -q set podkop.main=main
uci -q set podkop.main.connection_type='vpn'
uci -q set podkop.main.interface='awg0'
uci -q set podkop.main.community_lists='block cloudflare discord telegram'

# Cache keys must match Guard's 'main-<category>-community-ruleset' tags.
# Seed via real remote rule-set downloads to an actual bbolt cache.db.
jq -n \
  --arg base 'http://127.0.0.1:18877' \
  --arg cache '/tmp/sing-box/cache.db' '
  ["block","cloudflare","discord","telegram"]
  | map({
      type:"remote",
      tag:("main-" + . + "-community-ruleset"),
      format:"binary",
      url:($base + "/" + . + ".srs"),
      update_interval:"8760h",
      download_detour:"direct"
    }) as $sets
  | {
      log:{level:"info"},
      outbounds:[{type:"direct",tag:"direct"}],
      route:{
        rules:[{action:"route",rule_set:($sets|map(.tag)),outbound:"direct"}],
        rule_set:$sets,
        final:"direct"
      },
      experimental:{cache_file:{enabled:true,path:$cache,store_fakeip:false}}
    }
' > "$TEST_DIR/seed.json"
sing-box check -c "$TEST_DIR/seed.json"
rm -f /tmp/sing-box/cache.db
sing-box run -c "$TEST_DIR/seed.json" > "$TEST_DIR/seed.log" 2>&1 &
SING_PID=$!
ready=0
i=0
while [ "$i" -lt 35 ]; do
    if grep -q 'sing-box started' "$TEST_DIR/seed.log" &&
       [ -s /tmp/sing-box/cache.db ]; then
        ready=1
        break
    fi
    if ! kill -0 "$SING_PID" 2>/dev/null; then break; fi
    sleep 1
    i=$((i + 1))
done
if [ "$ready" -ne 1 ]; then
    echo 'FAIL: real sing-box could not seed cache' >&2
    tail -n 60 "$TEST_DIR/seed.log" >&2
    exit 1
fi
echo PASS_REAL_SINGBOX_CACHE_SEED

# Guard's refresh-test copies the live cache and launches a second sing-box
# with a dead SOCKS outbound. It should succeed ONLY for cached rule sets.
export PODKOP_GUARD_DIR="$STATE"
export PODKOP_GUARD_RELEASE_BASE='http://127.0.0.1:18877'
export PODKOP_GUARD_NICE_LEVEL=0
export PODKOP_GUARD_CACHE_TEST_TIMEOUT=14
if ! sh /mnt/pg-bundle/podkop-guard refresh-test \
    > "$TEST_DIR/positive.log" 2>&1; then
    echo 'FAIL: real 4-list refresh-test' >&2
    tail -n 95 "$TEST_DIR/positive.log" >&2
    exit 1
fi
grep -q 'candidate cache passed offline cold-start validation' "$TEST_DIR/positive.log"
grep -q 'refresh test passed; persistent LKG was not changed' "$TEST_DIR/positive.log"
for tag in block cloudflare discord telegram; do
    grep -q "downloaded $tag.srs directly" "$TEST_DIR/positive.log"
done
verify_unchanged
echo PASS_REAL_FOUR_SRS_REFRESH_TEST
echo PASS_REAL_LKG_PRESERVED_POSITIVE

# Fifth file is valid and served, but absent from the sing-box cache.
# The verifier must not confuse starting the process with having all tags.
uci -q set podkop.main.community_lists='block cloudflare discord telegram geoblock'
if sh /mnt/pg-bundle/podkop-guard refresh-test \
    > "$TEST_DIR/missing-cache.log" 2>&1; then
    echo 'FAIL: incomplete 4/5 sing-box cache was accepted' >&2
    cat "$TEST_DIR/missing-cache.log" >&2
    exit 1
fi
grep -q 'downloaded geoblock.srs directly' "$TEST_DIR/missing-cache.log"
grep -q 'candidate LKG passed compile/decompile round-trip' "$TEST_DIR/missing-cache.log" || {
    echo 'FAIL: missing-cache case rejected before reaching cache verification' >&2
    cat "$TEST_DIR/missing-cache.log" >&2
    exit 1
}
grep -Eq 'candidate cache failed offline cold-start validation|candidate cache validation timed out' "$TEST_DIR/missing-cache.log" || {
    echo 'FAIL: missing-cache case rejected for an unrelated reason' >&2
    cat "$TEST_DIR/missing-cache.log" >&2
    exit 1
}
verify_unchanged
echo PASS_REAL_MISSING_FIFTH_CACHE_REJECTED
echo PASS_REAL_LKG_PRESERVED_NEGATIVE

# Any missing upstream SRS must fail before cache validation or persistent writes.
uci -q set podkop.main.community_lists='block cloudflare discord telegram not-a-real-category'
if sh /mnt/pg-bundle/podkop-guard refresh-test \
    > "$TEST_DIR/missing-source.log" 2>&1; then
    echo 'FAIL: nonexistent upstream rule-set accepted' >&2
    exit 1
fi
grep -q 'cannot download required Community SRS: not-a-real-category' "$TEST_DIR/missing-source.log" || {
    echo 'FAIL: missing-source case failed unexpectedly' >&2
    cat "$TEST_DIR/missing-source.log" >&2
    exit 1
}
verify_unchanged
echo PASS_REAL_MISSING_SOURCE_REJECTED

echo OPENWRT_MULTI_SRS_CACHE_E2E_PASS
